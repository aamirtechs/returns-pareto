import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Mini-bundler for this ES module codebase: transforms src/index.js into a
// browser bundle and emits docs/app.js, so the browser app runs the exact same
// core code as the library and CLI. No dependencies, no build tooling beyond
// Node. Excludes src/cli.js, which is Node-only (fs, process and file output).
// The fs import is replaced with a stub that throws: the file-loading helpers
// (loadOrders, loadReturns, loadReasonMap) are Node-only, while every pure
// function (parseCsv, normaliseOrders, normaliseReturns, bucketReason,
// analyse, buildReport, paretoToCsv) works on text already read in the page.

const root = path.dirname(fileURLToPath(import.meta.url));
const SRC_FILE = path.join(root, 'src', 'index.js');
const OUT = path.join(root, 'docs', 'app.js');

let code = fs.readFileSync(SRC_FILE, 'utf8');
const exported = [];
code = code.replace(/^export function (\w+)/gm, (m, name) => { exported.push(name); return 'function ' + name; });
code = code.replace(/^import fs from "node:fs";$/m,
  'const fs = { readFileSync: function () { throw new Error("File loading is Node-only. In the browser, read the file in the page and pass its text to parseCsv."); } };');

const header = '/* returns-pareto browser bundle. Generated by build-web.js from src/. Do not edit by hand. */\n' + "'use strict';\n";
const footer = '\nwindow.ReturnsPareto = { ' + exported.map((n) => n + ': ' + n).join(', ') + ' };\n';

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, header + code + footer, 'utf8');
console.log('Wrote ' + path.relative(process.cwd(), OUT) + ' with ' + exported.length + ' exported functions.');
